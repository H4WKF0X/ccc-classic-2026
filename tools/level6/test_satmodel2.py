"""Soundness tests for satmodel2 (safeguard 2 of the stronger-model task).

Every test fixes a whole trajectory (positions + on-flags per emitter and tick) and asks satmodel2
whether it is a solution.  A stronger model may only reject trajectories that are *not canonical*
(symmetry / dominance, group B), never a real program, so each program is tested twice:

  base : the projected trajectory as is, symbreak=False (groups A only), plus the exact detection
         ticks of the reference simulator forced on the model's det variables -> must be FEASIBLE;
         with one copy more than the simulator made -> must be INFEASIBLE (model not too loose).
  canon: the trajectory canonicalised by `canonicalize` below (an independent implementation of the
         dominance / symmetry argument), replayed in the simulator (same detection ticks),
         then fixed in the full model (symbreak=True, plus proven bounds `known`) -> FEASIBLE.

Programs: every distinct program in work/level6/pool/** and best/ (small, medium; large sampled),
the whole program (real start, F-question) and the stretches between detections (free start,
W-questions, k = 1..3), and random trajectories (real and free start, any number of copies).

usage: test_satmodel2.py pool --keys 1-small,2-medium [--large-sample 300] [--procs 4]
       test_satmodel2.py random --n 2000 [--procs 4]
Writes one JSON line per failing test plus a summary to results/level6/test_satmodel2_<mode>.jsonl.
"""
import argparse, csv, glob, json, os, random, sys, time
from multiprocessing import Pool
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lines import LineGeo, load, simulate, program_from_states, parse_in, parse_out, L6
from multi_cycles import det_ticks_of
from exact import project
import satmodel2

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, 'results', 'level6')


# ---------------------------------------------------------------- independent reference code
def sim_lines(lg, states):
    """Detection ticks of a line-coordinate trajectory (t=0..T), pattern + halo empty at t=0.
    Independent of the CP-SAT model; cross-checked against cycles.simulate for real starts."""
    S, K = lg.S, lg.K
    sS, sK = set(S), set(K)
    mat = set()
    dets = []
    for t in range(1, len(states)):
        q, o = states[t]
        ln = [q[e] - 1 if o[e] and 1 <= q[e] <= lg.nl else None for e in range(6)]
        for u in S + K:
            h = sum(1 for e in range(6) if ln[e] is not None and ln[e] == u[e % 3])
            if h == 2:
                mat.add(u)
            elif h >= 3:
                mat.discard(u)
        if sS <= mat and not (sK & mat):
            mat -= sS
            dets.append(t)
    return dets


def group(lg):
    """All elements (img, rev) of the group generated by twin swaps and pattern automorphisms."""
    gens = []
    for a in range(3):
        img = list(range(6))
        img[a], img[a + 3] = a + 3, a
        gens.append((tuple(img), (0,) * 6))
    for perm, rev in satmodel2.automorphisms(lg):
        gens.append((tuple(perm[e % 3] + 3 * (e // 3) for e in range(6)), tuple(rev[e % 3] for e in range(6))))
    ident = (tuple(range(6)), (0,) * 6)
    G = {ident}
    frontier = [ident]
    while frontier:
        nxt = []
        for g in frontier:
            for h in gens:      # g then h
                img = tuple(h[0][g[0][e]] for e in range(6))
                rev = tuple(g[1][e] ^ h[1][g[0][e]] for e in range(6))
                if (img, rev) not in G:
                    G.add((img, rev))
                    nxt.append((img, rev))
        frontier = nxt
    return G


def canonicalize(lg, states, free):
    """Representative of `states` that satisfies satmodel2's group-B rules, firing the same beams."""
    T = len(states) - 1
    nq = lg.nq
    q = [[states[t][0][e] for t in range(T + 1)] for e in range(6)]
    o = [[bool(states[t][1][e]) for t in range(T + 1)] for e in range(6)]
    if free and T >= 1:
        for e in range(6):
            q[e][0], o[e][0] = q[e][1], o[e][1]
    U = lg.S + lg.K

    def stretches(e, litq):
        lit = [o[e][t] and q[e][t] in litq for t in range(T + 1)]
        tog = [False] + [o[e][t] != o[e][t - 1] for t in range(1, T + 1)]
        t = 0
        while t <= T:
            if lit[t]:
                t += 1
                continue
            a0 = t
            b = t
            while b + 1 <= T and not lit[b + 1] and not tog[b + 1]:
                b += 1
            qa, qb = q[e][a0], q[e][b]
            for s in range(a0, b + 1):
                if free and a0 == 0:
                    q[e][s] = qb
                elif b == T:
                    q[e][s] = qa
                else:
                    step = min(s - a0, abs(qb - qa))
                    q[e][s] = qa + (step if qb >= qa else -step)
            t = b + 1

    for e in range(6):
        a = e % 3
        litq = {u[a] + 1 for u in U}
        while True:             # fixpoint of stretch rewriting and toggle/move swaps (B2, B2b)
            stretches(e, litq)
            changed = False
            for t in range(1, T):
                lit_t = o[e][t] and q[e][t] in litq
                if (o[e][t] != o[e][t - 1] and q[e][t + 1] != q[e][t] and not lit_t
                        and (not o[e][t - 1] or q[e][t + 1] not in litq)):
                    q[e][t], o[e][t] = q[e][t + 1], o[e][t - 1]
                    changed = True
                    break
            if not changed:
                break
    t0 = 0 if free else 1
    best = None
    for img, rev in group(lg):
        Y = [None] * 6
        for e in range(6):
            Y[img[e]] = [((nq - 1 - q[e][t]) if rev[e] else q[e][t], o[e][t]) for t in range(T + 1)]
        key = [2 * Y[e][t][0] + int(Y[e][t][1]) for e in range(6) for t in range(t0, T + 1)]
        if best is None or key < best[0]:
            best = (key, Y)
    Y = best[1]
    return [([Y[e][t][0] for e in range(6)], [Y[e][t][1] for e in range(6)]) for t in range(T + 1)]


def fixed(states, dets=None):
    def extra(m, V):
        for t, (q, o) in enumerate(states):
            for e in range(6):
                m.Add(V['pos'][e][t][q[e]] == 1)
                m.Add(V['on'][e][t] == int(o[e]))
        if dets is not None:
            ds = set(dets)
            for t in range(1, len(states)):
                m.Add(V['det'][t] == int(t in ds))
    return extra


# ---------------------------------------------------------------- proven bounds per case
def proven_bounds(key):
    """{case: {'F': {j: lb}, 'W': {k: lb}}} from decomp_<key>.csv and exact_<key>.csv (INFEASIBLE
    rows: F_count >= best_then).  Only lower bounds, which are proven by the exact model."""
    out = {}
    p = os.path.join(RES, f'decomp_{key}.csv')
    if os.path.exists(p):
        for r in csv.DictReader(open(p)):
            c = int(r['case'])
            d = out.setdefault(c, {'F': {}, 'W': {}})
            for n in ('F', 'W'):
                for a, b in json.loads(r[n]).items():
                    d[n][int(a)] = max(d[n].get(int(a), 0), b)
    p = os.path.join(RES, f'exact_{key}.csv')
    cases = parse_in(f'{L6}/in/in_level-6_{key}.txt')
    if os.path.exists(p):
        for r in csv.DictReader(open(p)):
            if r['status'] == 'INFEASIBLE':
                c = int(r['case'])
                d = out.setdefault(c, {'F': {}, 'W': {}})
                n = cases[c][2]
                d['F'][n] = max(d['F'].get(n, 0), int(r['T']) + 1)
    p = os.path.join(RES, 'close_medium.jsonl')
    if key == '2-medium' and os.path.exists(p):
        for line in open(p):
            rr = json.loads(line)
            if rr['status'] == 'INFEASIBLE':
                d = out.setdefault(rr['case'], {'F': {}, 'W': {}})
                d['W'][rr['k']] = max(d['W'].get(rr['k'], 0), rr['T'] + 1)
    return out


# ---------------------------------------------------------------- one test
def check(lg, states, k, free, dets, known, tag):
    """Run base + canon tests on one trajectory; return list of failure dicts."""
    T = len(states) - 1
    fails = []
    if known:
        F, W = satmodel2.closure(known.get('F'), known.get('W'), k + 1)
        if (W if free else F).get(k, 0) == T:
            C3[0] += 1                  # the "T is minimal" rules are active in this test
    start = (states[0][0], states[0][1]) if free else None
    s, _ = satmodel2.solve(lg, T, k, start_cfg=start, symbreak=False, extra=fixed(states, dets), secs=60)
    if s != 'FEASIBLE':
        fails.append(dict(tag=tag, test='base', status=s))
    s, _ = satmodel2.solve(lg, T, len(dets) + 1, start_cfg=start, symbreak=False, extra=fixed(states), secs=60)
    if s != 'INFEASIBLE':
        fails.append(dict(tag=tag, test='base+1', status=s))
    cs = canonicalize(lg, states, free)
    cd = sim_lines(lg, cs)
    if cd != dets:
        fails.append(dict(tag=tag, test='canon-replay', status=f'{cd} != {dets}'))
    s, _ = satmodel2.solve(lg, T, k, free_start=free, symbreak=True, known=known, extra=fixed(cs, dets), secs=60)
    if s != 'FEASIBLE':
        fails.append(dict(tag=tag, test='canon', status=s))
    return fails


C3 = [0]


def test_program(job):
    """job = (key, case, program lines).  Whole program + stretches between detections."""
    key, case, prog, kmax = job
    cases = parse_in(f'{L6}/in/in_level-6_{key}.txt')
    r, g, count = cases[case]
    lg = LineGeo(r, g)
    known = BOUNDS.get(key, {}).get(case)
    st = project(lg, prog)
    if st is None:
        return dict(n=0, skipped=1, fails=[])
    dets = sim_lines(lg, st)
    ref = det_ticks_of(lg.geo, prog)
    if dets != ref:
        return dict(n=0, skipped=0, fails=[dict(tag=(key, case), test='sim_lines', status=f'{dets} vs {ref}')])
    fails, n = [], 0
    T = len(prog)
    # whole program (real start)
    fails += check(lg, st, count, False, dets, known, (key, case, 'F', count, T))
    n += 1
    # stretches between detections: free start, j copies
    for i in range(len(dets)):
        for j in range(1, kmax + 1):
            if i + j > len(dets):
                break
            seg = st[dets[i - 1] if i else 0: dets[i + j - 1] + 1]
            if i == 0:          # prefix: real start, j copies
                sd = dets[:j]
                fails += check(lg, seg, j, False, sd, known, (key, case, 'F', j, len(seg) - 1))
            else:
                sd = [d - dets[i - 1] for d in dets[i:i + j]]
                fails += check(lg, seg, j, True, sd, known, (key, case, 'W', j, len(seg) - 1, i))
            n += 1
    return dict(n=n, skipped=0, fails=fails, c3=C3[0], pid=os.getpid())


def random_traj(lg, T, free, rnd):
    nq = lg.nq
    if free:
        q = [rnd.randrange(nq) for _ in range(6)]
        o = [rnd.random() < 0.5 for _ in range(6)]
    else:
        q, o = [lg.start_q] * 6, [False] * 6
    states = [(list(q), list(o))]
    pmove, ptog = rnd.choice([(0.3, 0.2), (0.5, 0.1), (0.2, 0.4)])
    for t in range(T):
        for e in range(6):
            x = rnd.random()
            if x < ptog:
                o[e] = not o[e]
            elif x < ptog + pmove:
                q[e] = min(nq - 1, max(0, q[e] + rnd.choice((-1, 1))))
        states.append((list(q), list(o)))
    return states


def mutate_traj(lg, states, rate, rnd, i0, i1):
    """Replay the per-tick actions (move -1/0/+1 or toggle) of states[i0..i1], each replaced by a
    random action with probability `rate`; positions are clamped to the arc."""
    nq = lg.nq
    q, o = list(states[i0][0]), list(states[i0][1])
    out = [(list(q), list(o))]
    for t in range(i0 + 1, i1 + 1):
        for e in range(6):
            if states[t][1][e] != states[t - 1][1][e]:
                act = 'T'
            else:
                act = states[t][0][e] - states[t - 1][0][e]
            if rnd.random() < rate:
                act = rnd.choice(['T', -1, 0, 1])
            if act == 'T':
                o[e] = not o[e]
            else:
                q[e] = min(nq - 1, max(0, q[e] + act))
        out.append((list(q), list(o)))
    return out


def test_random(job):
    key, case, seed = job
    rnd = random.Random(seed)
    cases = parse_in(f'{L6}/in/in_level-6_{key}.txt')
    r, g, count = cases[case]
    lg = LineGeo(r, g)
    known = BOUNDS.get(key, {}).get(case)
    kind = 'walk'
    st = None
    if rnd.random() < 0.7:
        st = project(lg, BEST[key][case])
    if st is not None:
        # mutation of the best program: real start (prefix) or a stretch starting at a detection
        dets0 = sim_lines(lg, st)
        free = rnd.random() < 0.5 and len(dets0) >= 2
        i0 = rnd.choice(dets0[:-1]) if free else 0
        i1 = min(len(st) - 1, i0 + rnd.randint(2, 30))
        states = mutate_traj(lg, st, rnd.choice([0.0, 0.02, 0.05, 0.1, 0.3]), rnd, i0, i1)
        kind = 'mutant'
    else:
        free = rnd.random() < 0.5
        states = random_traj(lg, rnd.randint(3, 25), free, rnd)
    T = len(states) - 1
    dets = sim_lines(lg, states)
    fails = []
    if not free:
        prog = program_from_states(lg, states[1:])
        ref = det_ticks_of(lg.geo, prog)
        if ref != dets:
            fails.append(dict(tag=(key, case, seed), test='sim_lines', status=f'{dets} vs {ref}'))
    # free-start trajectories are W-type: pattern + halo empty at t=0 (sim_lines assumes the same)
    fails += check(lg, states, len(dets), free, dets, known, (key, case, seed, kind, 'free' if free else 'real', T))
    return dict(n=1, copies=len(dets), free=free, fails=fails, c3=C3[0], pid=os.getpid())


BOUNDS = {}
BEST = {}


def init_bounds(keys):
    for k in keys:
        BOUNDS[k] = proven_bounds(k)
        BEST[k] = parse_out(f'{L6}/best/out_level-6_{k}.txt')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('mode', choices=['pool', 'random'])
    ap.add_argument('--keys', default='1-small,2-medium')
    ap.add_argument('--large-sample', type=int, default=0)
    ap.add_argument('--kmax', type=int, default=2)
    ap.add_argument('--n', type=int, default=2000)
    ap.add_argument('--procs', type=int, default=4)
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--limit', type=int, default=0, help='max programs (debug)')
    a = ap.parse_args()
    keys = a.keys.split(',') + (['3-large'] if a.large_sample else [])
    init_bounds(keys)
    out = os.path.join(RES, f'test_satmodel2_{a.mode}.jsonl')
    jobs = []
    if a.mode == 'pool':
        for key in keys:
            ncase = len(parse_in(f'{L6}/in/in_level-6_{key}.txt'))
            files = sorted(glob.glob(f'{L6}/pool/**/{key}*.txt', recursive=True))
            files.append(f'{L6}/best/out_level-6_{key}.txt')
            seen = set()
            cases = parse_in(f'{L6}/in/in_level-6_{key}.txt')
            for fn in files:
                progs = parse_out(fn)
                if len(progs) != ncase:
                    print(f'skip {fn}: {len(progs)} programs for {ncase} cases', flush=True)
                    continue
                for c, p in enumerate(progs):
                    lg_geo = LineGeo(cases[c][0], cases[c][1]).geo
                    n = simulate(lg_geo, p, cases[c][2])
                    if n is None:
                        continue                # not a valid program for this case
                    p = p[:n]
                    sig = (c, tuple(' '.join(x) for x in p))
                    if sig in seen:
                        continue
                    seen.add(sig)
                    jobs.append((key, c, p, a.kmax))
            if key == '3-large':
                rnd = random.Random(a.seed)
                lj = [j for j in jobs if j[0] == '3-large']
                keep = set(map(id, rnd.sample(lj, min(a.large_sample, len(lj)))))
                jobs = [j for j in jobs if j[0] != '3-large' or id(j) in keep]
        fn = test_program
    else:
        rnd = random.Random(a.seed)
        pick = []
        for key in keys:
            cases = parse_in(f'{L6}/in/in_level-6_{key}.txt')
            for c, (r, g, cnt) in enumerate(cases):
                cells = sum(row.count('M') for row in g)
                pick.append((key, c))
        jobs = [(*rnd.choice(pick), rnd.randrange(10 ** 9)) for _ in range(a.n)]
        fn = test_random
    if a.limit:
        jobs = jobs[:a.limit]
    print(f'{len(jobs)} jobs', flush=True)
    t0 = time.time()
    tot = dict(jobs=0, tests=0, skipped=0, fails=0, copies_ge1=0, free=0, c3=0)
    c3w = {}
    with Pool(a.procs, initializer=init_bounds, initargs=(keys,)) as pool, open(out, 'a') as f:
        for i, res in enumerate(pool.imap_unordered(fn, jobs, chunksize=1)):
            tot['jobs'] += 1
            tot['tests'] += res['n']
            tot['skipped'] += res.get('skipped', 0)
            tot['copies_ge1'] += int(res.get('copies', 0) >= 1)
            tot['free'] += int(res.get('free', False))
            c3w[res.get('pid')] = res.get('c3', 0)
            tot['c3'] = sum(c3w.values())
            for x in res['fails']:
                tot['fails'] += 1
                f.write(json.dumps(x, default=str) + '\n')
                f.flush()
                print('FAIL', x, flush=True)
            if (i + 1) % 100 == 0:
                print(f'{i + 1}/{len(jobs)} {tot} {time.time() - t0:.0f}s', flush=True)
        tot['secs'] = round(time.time() - t0)
        tot['mode'] = a.mode
        tot['keys'] = keys
        f.write(json.dumps(dict(summary=tot)) + '\n')
    print('SUMMARY', tot, flush=True)


if __name__ == '__main__':
    main()
